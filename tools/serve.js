// Minimaler statischer Dateiserver ohne Abhaengigkeiten, fuer lokales Testen.
//
// Hinweis: Fuer die echte PWA-Installation (Offline-Betrieb, "App installieren")
// verlangt Chrome einen vertrauenswuerdigen HTTPS-Ursprung. Ein lokaler Server im
// WLAN erfuellt das nicht – auch nicht mit selbstsigniertem Zertifikat. Die App
// wird deshalb ueber GitHub Pages ausgeliefert; dieser Server dient nur zum
// schnellen Ausprobieren am Rechner.
const http = require('http');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PORT = process.env.PORT || 8080;

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.webmanifest': 'application/manifest+json; charset=utf-8',
  '.png': 'image/png',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon',
};

const server = http.createServer((req, res) => {
  let urlPath = decodeURIComponent(req.url.split('?')[0]);
  if (urlPath.endsWith('/')) urlPath += 'index.html';
  const filePath = path.join(ROOT, urlPath);

  if (!filePath.startsWith(ROOT)) { res.writeHead(403); res.end('Forbidden'); return; }

  fs.readFile(filePath, (err, data) => {
    if (err) {
      res.writeHead(404, { 'Content-Type': 'text/plain' });
      res.end('Not found: ' + urlPath);
      return;
    }
    const ext = path.extname(filePath);
    res.writeHead(200, {
      'Content-Type': MIME[ext] || 'application/octet-stream',
      'Cache-Control': 'no-cache',
    });
    res.end(data);
  });
});

server.listen(PORT, () => console.log(`Server läuft: http://localhost:${PORT}`));
